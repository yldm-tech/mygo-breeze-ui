// Command breeze-ui discovers Breeze UI for MyGo: its components, the platforms they follow, and snippets that use them.
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime/debug"
	"strings"

	breeze "github.com/yldm-tech/mygo-breeze-ui/ui/breeze"
)

const usage = `breeze-ui is the CLI for github.com/yldm-tech/mygo-breeze-ui/ui/breeze.

Usage:

  breeze-ui list [-kind component|platform]
  breeze-ui add <component> [-o path]
  breeze-ui init [dir] [--force]
  breeze-ui example
  breeze-ui version
`

// version is the release's tag, which the Release workflow sets with -ldflags "-X main.version=v0.4.0" when it builds the binaries it attaches to the GitHub release.
var version string

// currentVersion is the version this command was built as: the release's tag for a release binary, the module's version for one built by go install ...@v0.4.0, or "devel" for one built from a checkout.
func currentVersion() string {
	if version != "" {
		return version
	}
	if info, ok := debug.ReadBuildInfo(); ok && info.Main.Version != "" && info.Main.Version != "(devel)" {
		return info.Main.Version
	}
	return "devel"
}

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "breeze-ui:", err)
		os.Exit(1)
	}
}

func run(args []string, out io.Writer) error {
	if len(args) == 0 || args[0] == "help" || args[0] == "-h" || args[0] == "--help" {
		_, _ = io.WriteString(out, usage)
		return nil
	}
	switch args[0] {
	case "list":
		return list(args[1:], out)
	case "add":
		return add(args[1:], out)
	case "init":
		return initProject(args[1:], out)
	case "example":
		_, _ = io.WriteString(out, example)
		return nil
	case "version", "-version", "--version":
		_, err := fmt.Fprintln(out, "breeze-ui", currentVersion())
		return err
	default:
		return fmt.Errorf("unknown command %q; run breeze-ui --help", args[0])
	}
}

func list(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("list", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	kind := fs.String("kind", "", "filter by component or platform")
	if err := fs.Parse(normalizeFlagArgs(args, map[string]bool{"-kind": true, "--kind": true})); err != nil {
		return err
	}
	if fs.NArg() != 0 {
		return errors.New("list takes no positional arguments")
	}
	for _, item := range breeze.Catalog() {
		if *kind != "" && item.Kind != *kind {
			continue
		}
		switch {
		case item.Kind == "component":
			fmt.Fprintf(out, "%s\t%s\t%s\n", item.Kind, item.Name, item.Look)
		case item.Value != "":
			fmt.Fprintf(out, "%s\t%s\t%s\n", item.Kind, item.Name, item.Value)
		default:
			fmt.Fprintf(out, "%s\t%s\n", item.Kind, item.Name)
		}
	}
	return nil
}

func add(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("add", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	path := fs.String("o", "", "write the snippet to a file instead of stdout")
	if err := fs.Parse(normalizeFlagArgs(args, map[string]bool{"-o": true, "--o": true, "--output": true})); err != nil {
		return err
	}
	if fs.NArg() != 1 {
		return errors.New("add requires one component name")
	}
	item, ok := breeze.FindKind("component", fs.Arg(0))
	if !ok {
		return fmt.Errorf("unknown component %q; run breeze-ui list -kind component", fs.Arg(0))
	}
	snippet := fmt.Sprintf("// Generated by breeze-ui add %s.\n// Package breeze: github.com/yldm-tech/mygo-breeze-ui/ui/breeze\n\n%s\n", item.Name, item.Example)
	return writeOutput(*path, snippet, out)
}

func initProject(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	fs.SetOutput(io.Discard)
	force := fs.Bool("force", false, "replace generated files")
	if err := fs.Parse(normalizeFlagArgs(args, map[string]bool{"--force": false})); err != nil {
		return err
	}
	if fs.NArg() > 1 {
		return errors.New("init takes at most one directory")
	}
	dir := "."
	if fs.NArg() == 1 {
		dir = fs.Arg(0)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	config := "{\n  \"library\": \"github.com/yldm-tech/mygo-breeze-ui/ui/breeze\",\n  \"catalogVersion\": 2\n}\n"
	path := filepath.Join(dir, "breeze-ui.json")
	if !*force {
		if _, err := os.Stat(path); err == nil {
			return fmt.Errorf("%s already exists; pass --force to replace it", path)
		} else if !os.IsNotExist(err) {
			return err
		}
	}
	if err := os.WriteFile(path, []byte(config), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(out, "created %s\n", path)
	return nil
}

// normalizeFlagArgs lets users put options before or after positional
// arguments. The standard flag package stops parsing at the first positional
// argument, while commands such as `breeze-ui add Button -o button.go` are a
// natural spelling for a CLI. Values belonging to known options stay next to
// their option; positionals are moved to the end in their original order.
func normalizeFlagArgs(args []string, valueFlags map[string]bool) []string {
	flags := make([]string, 0, len(args))
	positionals := make([]string, 0, len(args))
	for i := 0; i < len(args); i++ {
		arg := args[i]
		if !strings.HasPrefix(arg, "-") || arg == "-" {
			positionals = append(positionals, arg)
			continue
		}
		flags = append(flags, arg)
		name := arg
		if equals := strings.IndexByte(arg, '='); equals >= 0 {
			name = arg[:equals]
		}
		if valueFlags[name] && !strings.ContainsRune(arg, '=') && i+1 < len(args) {
			flags = append(flags, args[i+1])
			i++
		}
	}
	return append(flags, positionals...)
}

func writeOutput(path, content string, out io.Writer) error {
	if path == "" {
		_, err := io.WriteString(out, content)
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil && !errors.Is(err, os.ErrExist) {
		return err
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(out, "wrote %s\n", path)
	return nil
}

const example = `package main

import (
    "github.com/egoist/mygo/ui"
    breeze "github.com/yldm-tech/mygo-breeze-ui/ui/breeze"
)

// view draws macOS controls on a Mac, Windows 11 controls on Windows and GNOME controls on Linux.
func view(c *ui.Context) {
    breeze.Use(c) // the platform's colors and metrics, for package ui's widgets too
    ui.Column(c).Padding(16).Gap(12).Children(func() {
        breeze.Checkbox(c, &remember, "Remember me")
        breeze.Switch(c, &sync).Label("Sync")
        ui.Row(c).Gap(8).Children(func() {
            breeze.Button(c, "Cancel")
            if breeze.PrimaryButton(c, "Continue").Clicked() {
                // handle the action
            }
        })
    })
}
`
